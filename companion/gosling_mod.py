"""Устройство мода Gosling.esp — общее для сборщика (tools/build_gosling_esp.py) и сервиса.

Номера форм — локальные (без индекса мода в списке загрузки): в игре плагин ищет их через
TESDataHandler::LookupForm(номер, "Gosling.esp"). В C++ они продублированы в skse_plugin/src/Voice.cpp.
"""

PLUGIN = "Gosling.esp"
# Свой тип голоса для реплик сервиса (как MantellaVoice00 у Mantella): на время Say() Гослингу ставится
# он, файлы лежат в его папке. Обычный голос Гослинга (бой, «веди») — MaleYoungEager Эрика, шаблоном.
VOICE_TYPE = "GoslingVoice"
VOICE_TYPE_ID = 0x814

NPC = 0x800          # GoslingNPC — базовая запись
RELATIONSHIP = 0x801
NPC_REF = 0x802      # сам Гослинг в мире (постоянная ссылка)
VOICE_QUEST = 0x803  # квест-контейнер для тем-заглушек

QUEST_EDID = "GoslingVQ"
# Две темы-заглушки по одной реплике: (тема, реплика, EditorID темы). Чередуем их: если сказать одну
# тему дважды подряд, игра может проиграть старый звук из кэша.
LINES = [(0x810, 0x811, "GoslingLine1"), (0x812, 0x813, "GoslingLine2")]

# Поход к месту (приказ go_to): квест с алиасами «Путник» (Гослинг) и «Цель» (маркер карты); на «Путнике» — пакет
# «путешествуй к алиасу Цель». Приоритет квеста выше квеста спутника — пакет перебивает следование за игроком.
# Пакет игра ведёт и вне загруженной области (PathToReference туда не ходит). Номера — и в GoslingOrders.psc.
TRAVEL_QUEST = 0x815
TRAVEL_QUEST_EDID = "GoslingTravelQuest"
TRAVEL_PACKAGE = 0x816
TRAVELER_ALIAS = 0
DESTINATION_ALIAS = 1
# Режим «Веди»: тот же квест, алиас «Ведущий» с пакетом «сопроводи игрока к алиасу Цель» — ждёт, если игрок отстал.
LEAD_PACKAGE = 0x817
LEADER_ALIAS = 2
# Разговоры Гослинга с NPC (companion/talk.py): свои темы-заглушки для реплик NPC — звук по ЕГО типу голоса
# (Sound\Voice\Gosling.esp\<тип голоса NPC>\...), заглушки — под каждый тип голоса игры. Отдельно от тем Гослинга:
# одну тему подряд игра может проиграть из кэша. Номера — и в skse_plugin/src/Voice.cpp.
NPC_LINES = [(0x818, 0x819, "GoslingNpc1"), (0x81A, 0x81B, "GoslingNpc2")]
# Подойти к человеку (исследователь): тот же квест, алиас «Подходящий» с пакетом «следуй за алиасом Цель» в паре шагов —
# человек идёт, Гослинг идёт за ним, а не останавливается (пакет похода стоял в ~7 м, и ушедший — «дороги нет», 24.10).
APPROACH_PACKAGE = 0x81C
APPROACHER_ALIAS = 3
# Побыть здесь (исследователь): алиас «Слушающий» с пакетом «будь где-нибудь рядом с алиасом Цель» (Sandbox) — постоять,
# посидеть, опереться о стену, пока вокруг говорят; Цель — метка, поставленная там, где он стоит.
LINGER_PACKAGE = 0x81D
LINGERER_ALIAS = 4
NEXT_OBJECT_ID = 0x81E


def voice_file(line: int, lines: list = LINES) -> str:
    """Имя .wav реплики: <квест>_<тема>_<formID реплики без индекса мода>_<номер ответа>.
    EditorID короткие (≤10 и ≤15 символов) — игра их не обрезает. lines — NPC_LINES: реплика NPC."""
    _, info, topic_edid = lines[line]
    return f"{QUEST_EDID}_{topic_edid}_{info:08X}_1.wav"
