"""Инструменты агента: справки, которые модель запрашивает сама, когда для ответа не хватает
обстановки из «Сейчас в игре». Тяжёлое и редкое (места на карте, позже — квесты, память, книги)
держим здесь, а не в каждом промпте.

Данные — из кэша сервиса (плагин присылает заранее), поэтому инструмент отвечает мгновенно.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING, Callable

from companion.game.places import PlaceBook
from companion.game.state import GameState
from companion.knowledge import Knowledge

if TYPE_CHECKING:  # память импортирует состояние игры — только для подсказок типов
    from companion.memory.keeper import MemoryKeeper


@dataclass
class Tool:
    name: str
    description: str
    parameters: dict  # JSON Schema аргументов
    handler: Callable[..., str]

    def schema(self) -> dict:
        return {"type": "function",
                "function": {"name": self.name, "description": self.description, "parameters": self.parameters}}


def place_info(places: PlaceBook, name: str) -> str:
    """Инструмент: справка о любом месте Скайрима из данных игры."""
    card = places.card(name or "")
    if card:
        return "Справка (что знает о месте любой местный; сам ты там мог и не бывать): " + card
    similar = [p.name for p in places.search(name or "")]
    if similar:
        return f"Места «{name}» точно не знаю. Похожие названия: " + ", ".join(similar) + "."
    return f"Места «{name}» не знаю."


def build_tools(game: GameState, places: PlaceBook | None = None, knowledge: Knowledge | None = None,
                memory: MemoryKeeper | None = None) -> list[Tool]:
    tools = [
        Tool(
            name="find_places",
            description=(
                "Найти места на карте игрока: по типу, части названия и/или расстоянию. Отвечает расстоянием "
                "и стороной света от игрока. Знает только открытые игроком места; неоткрытые — только "
                "совсем рядом и без названия. Вызывай, если спрашивают, где что-то находится, куда пойти, "
                "что есть поблизости — и этого нет в «Сейчас в игре»."),
            parameters={
                "type": "object",
                "properties": {
                    "kind": {"type": "string", "description": (
                        "Тип места, часть слова: город, поселение, пещера, форт, руины, шахта, ферма, лагерь, "
                        "логово дракона, святилище, камень-хранитель, маяк, перевал, хижина. Пусто — любые.")},
                    "name": {"type": "string", "description": "Часть названия места. Пусто — любое."},
                    "max_km": {"type": "number", "description": "Не дальше стольких км. 0 — без ограничения."},
                },
            },
            handler=game.find_places,
        ),
        Tool(
            name="quests",
            description=(
                "Все активные задания из журнала игрока: название, тип и текущие цели. Цели нескольких главных "
                "заданий уже есть в «Сейчас в игре»; эта справка — когда нужен весь список: «какие у нас "
                "задания?», «что ещё можно сделать?»."),
            parameters={"type": "object", "properties": {}},
            handler=game.quest_log.summary,
        ),
        Tool(
            name="quest_details",
            description=(
                "Заглянуть в журнал Владоса по одному заданию: текущие цели и последняя запись журнала — что "
                "произошло и что делать дальше. Ты спутник и можешь смотреть его журнал в любой момент. Вызывай "
                "сразу, как только спрашивают, что дальше по заданию, куда идти, как его выполнить, или просят "
                "«посмотри в журнале», «глянь сам» — не обещай посмотреть потом и не отсылай Владоса в журнал."),
            parameters={
                "type": "object",
                "properties": {"name": {"type": "string", "description": "Название квеста или его часть."}},
                "required": ["name"],
            },
            handler=game.quest_log.details,
        ),
        Tool(
            name="player_details",
            description=(
                "Заглянуть к Владосу в сумку и оглядеть его: золото, здоровье/магия/запас сил, что надето и в "
                "руках, что в сумке (по категориям, самое ценное), активные эффекты и болезни. Ты спутник и "
                "можешь это сделать в любой момент — это не кража. Вызывай сразу, как только речь о его вещах: "
                "«глянь, что у меня есть», «посмотрел, что в сумке?», «что продать?», «хватит ли денег?», "
                "«чем лечиться?», «что надеть?» — не отказывайся и не обещай посмотреть потом."),
            parameters={"type": "object", "properties": {}},
            handler=game.player_details,
        ),
    ]
    if places:
        tools.append(Tool(
            name="place_info",
            description=(
                "Справка о месте Скайрима по названию: что это (город, деревня, пещера, форт...), в каком "
                "владении, а для поселений — что в нём есть: лавки, таверна, кузница, храмы, гильдии, замок, "
                "и кто там живёт или работает. Про текущее место справка уже есть в «Сейчас в игре» — "
                "вызывай для других мест: «где в Рифтене купить зелья?», «что есть в Ривервуде?»."),
            parameters={
                "type": "object",
                "properties": {"name": {"type": "string", "description": "Название места, как в игре."}},
                "required": ["name"],
            },
            handler=lambda name="": place_info(places, name),
        ))
    if knowledge:
        tools.append(Tool(
            name="world_info",
            description=(
                "Что ты знаешь о Скайриме как местный — верные знания о мире, а не догадки: кто такой человек (где "
                "живёт, кем работает), что за место, боги и даэдра, народы, история, война, фракции, существа, "
                "а ещё что написано в книгах и записках, которые вы прочитали (Владос или ты сам). "
                "Вызывай, когда спрашивают о людях, местах или мире, а этого нет в «Сейчас в игре», — и отвечай по "
                "справке, своими словами. Спросили о прочитанной книге или записке («о чём она?», «что там "
                "написано?») — вызывай с её названием: содержание только здесь, по памяти ты его не перескажешь. "
                "Чего в справке нет — того ты не знаешь: так и скажи, не выдумывай."),
            parameters={
                "type": "object",
                "properties": {"query": {"type": "string", "description": (
                    "О чём вспомнить: имя, место, тема или название книги — «Лукан», «Седобородые», «двемеры», "
                    "«Кошки Скайрима».")}},
                "required": ["query"],
            },
            handler=lambda query="": knowledge.answer(query),
        ))
    if memory:
        tools.append(Tool(
            name="recall",
            description=(
                "Вспомнить ваше общее с Владосом прошлое: где вы были, что делали, что говорили ты и он, что слышали от "
                "людей, что узнали, о чём договорились, что ты ему уже предлагал и что он ответил. Вызывай, когда "
                "Владос спрашивает «помнишь…?», «где мы…?», «что сказал…?», «что мы делали в…?», «я тебе говорил…» "
                "— или тебе нужно проверить, было ли что-то. Отвечай по найденному; чего не нашлось — того ты не "
                "помнишь: так и скажи, не выдумывай. О мире вообще (люди, места, книги) — это world_info."),
            parameters={
                "type": "object",
                "properties": {"query": {"type": "string", "description": (
                    "Что вспомнить — ключевые слова: место, человек, вещь, дело: «золотой коготь», «Ветреный пик», "
                    "«Лукан», «дракон у башни».")}},
                "required": ["query"],
            },
            handler=lambda query="": memory.recall(query),
        ))
    return tools
